CREATE FUNCTION public.push_consume_wake(p_nonce uuid,p_timestamp bigint) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
 UPDATE public.push_worker_wakes SET consumed_at=now() WHERE nonce=p_nonce AND issued_at=p_timestamp
  AND abs(extract(epoch FROM now())-issued_at)<=120 AND consumed_at IS NULL;
 RETURN FOUND;
END $$;
