CREATE FUNCTION public.push_enqueue(p_user integer,p_kind text,p_target jsonb,p_key text,p_subscription bigint DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_event bigint;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM public.push_subscriptions s JOIN public.api_sessions a ON a.token_hash=s.session_hash AND a.user_id=s.user_id
   WHERE s.user_id=p_user AND a.expires_at>extract(epoch FROM now()) AND (p_subscription IS NULL OR s.id=p_subscription)
   AND (p_kind='test' OR s.preferences->>p_kind='true')) THEN RETURN; END IF;
 INSERT INTO public.push_events(user_id,kind,target,dedupe_key) VALUES(p_user,p_kind,p_target,p_key)
 ON CONFLICT(user_id,dedupe_key) DO NOTHING RETURNING id INTO v_event;
 IF v_event IS NULL THEN RETURN; END IF;
 INSERT INTO public.push_deliveries(event_id,subscription_id)
 SELECT v_event,s.id FROM public.push_subscriptions s JOIN public.api_sessions a ON a.token_hash=s.session_hash AND a.user_id=s.user_id
 WHERE s.user_id=p_user AND a.expires_at>extract(epoch FROM now()) AND (p_subscription IS NULL OR s.id=p_subscription)
 AND (p_kind='test' OR s.preferences->>p_kind='true');
 PERFORM public.push_wake_worker();
END $$;
REVOKE ALL ON FUNCTION public.push_enqueue(integer,text,jsonb,text,bigint) FROM PUBLIC,anon,authenticated;

CREATE FUNCTION public.push_target_allowed(p_user integer,p_kind text,p_target jsonb) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_team integer; v_player integer; v_event integer;
BEGIN
 IF p_kind='test' THEN RETURN true; END IF;
 IF p_kind='friends' THEN RETURN EXISTS(SELECT 1 FROM public.friend_requests WHERE id=(p_target->>'id')::bigint AND recipient_id=p_user AND status='pending'); END IF;
 v_team=(p_target->>'team_id')::integer; v_event=(p_target->>'event_id')::integer;
 IF p_target->>'mode'='coach' THEN
   RETURN EXISTS(SELECT 1 FROM public.team_memberships WHERE team_id=v_team AND user_id=p_user);
 END IF;
 v_player=(p_target->>'player_id')::integer;
 IF NOT EXISTS(SELECT 1 FROM public.portal_player_links l JOIN public.jokalariak j ON j.id_jokalaria=l.player_id AND j.id_taldea=l.team_id
  WHERE l.user_id=p_user AND l.player_id=v_player AND l.team_id=v_team) THEN RETURN false; END IF;
 IF p_kind='notices' THEN RETURN EXISTS(SELECT 1 FROM public.portal_notices WHERE id=(p_target->>'id')::bigint AND team_id=v_team); END IF;
 IF p_target->>'kind'='session' THEN RETURN EXISTS(SELECT 1 FROM public.saioak WHERE id_saio=v_event AND id_taldea=v_team); END IF;
 IF p_target->>'kind'='match' THEN
   RETURN EXISTS(SELECT 1 FROM public.partidak m WHERE m.id_partida=v_event AND m.id_taldea=v_team AND
     (p_target->>'reason'='withdrawn' OR EXISTS(SELECT 1 FROM public.portal_callups WHERE match_id=v_event AND player_id=v_player)));
 END IF;
 RETURN false;
END $$;
REVOKE ALL ON FUNCTION public.push_target_allowed(integer,text,jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.push_target_allowed(integer,text,jsonb) TO service_role;

CREATE FUNCTION public.push_device_action(p_user integer,p_session text,p_device text,p_action text,p_data jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_sub public.push_subscriptions%ROWTYPE;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM public.api_sessions WHERE token_hash=p_session AND user_id=p_user AND expires_at>extract(epoch FROM now())) THEN
  RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Saioa iraungi da; hasi berriro'; END IF;
 SELECT * INTO v_sub FROM public.push_subscriptions WHERE device_hash=p_device FOR UPDATE;
 IF p_action='status' THEN
  IF v_sub.id IS NULL OR v_sub.user_id<>p_user THEN RETURN jsonb_build_object('registered',false); END IF;
  UPDATE public.push_subscriptions SET session_hash=p_session WHERE id=v_sub.id;
  RETURN jsonb_build_object('registered',true,'endpoint',v_sub.endpoint,'binding',v_sub.binding,'preferences',v_sub.preferences,'language',v_sub.language);
 ELSIF p_action='remove' THEN
  DELETE FROM public.push_subscriptions WHERE device_hash=p_device AND user_id=p_user;
  RETURN jsonb_build_object('ok',true);
 ELSIF p_action='test' THEN
  IF v_sub.id IS NULL OR v_sub.user_id<>p_user THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='Aktibatu jakinarazpenak lehenik'; END IF;
  IF v_sub.last_test_at>now()-interval '1 minute' THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Itxaron minutu bat berriro probatu aurretik'; END IF;
  UPDATE public.push_subscriptions SET last_test_at=now() WHERE id=v_sub.id;
  PERFORM public.push_enqueue(p_user,'test',jsonb_build_object('mode','settings'),'test:'||gen_random_uuid()::text,v_sub.id);
  RETURN jsonb_build_object('ok',true);
 ELSIF p_action='save' THEN
  IF v_sub.id IS NOT NULL AND v_sub.user_id<>p_user THEN DELETE FROM public.push_deliveries WHERE subscription_id=v_sub.id; END IF;
  INSERT INTO public.push_subscriptions(user_id,device_hash,session_hash,endpoint,p256dh,auth,language,preferences)
   VALUES(p_user,p_device,p_session,p_data->>'endpoint',p_data->>'p256dh',p_data->>'auth',p_data->>'language',p_data->'preferences')
   ON CONFLICT(device_hash) DO UPDATE SET user_id=excluded.user_id,session_hash=excluded.session_hash,endpoint=excluded.endpoint,
    p256dh=excluded.p256dh,auth=excluded.auth,language=excluded.language,preferences=excluded.preferences,updated_at=now(),
    binding=CASE WHEN push_subscriptions.user_id<>excluded.user_id THEN gen_random_uuid()::text ELSE push_subscriptions.binding END
   RETURNING * INTO v_sub;
  RETURN jsonb_build_object('ok',true,'binding',v_sub.binding);
 END IF;
 RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='Ekintza ez da baliozkoa';
END $$;
REVOKE ALL ON FUNCTION public.push_device_action(integer,text,text,text,jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.push_device_action(integer,text,text,text,jsonb) TO service_role;

CREATE FUNCTION public.push_claim(p_limit integer DEFAULT 20) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_jobs jsonb;
BEGIN
 DELETE FROM public.push_events WHERE created_at<now()-interval '7 days';
 DELETE FROM public.push_subscriptions s WHERE NOT EXISTS(SELECT 1 FROM public.api_sessions a WHERE a.token_hash=s.session_hash AND a.user_id=s.user_id AND a.expires_at>extract(epoch FROM now()));
 UPDATE public.push_deliveries d SET state='dropped' FROM public.push_events e,public.push_subscriptions s
 WHERE d.event_id=e.id AND d.subscription_id=s.id AND d.state='queued' AND
 (e.created_at<now()-interval '1 day' OR d.attempts>=5 OR e.user_id<>s.user_id OR
 (e.kind<>'test' AND s.preferences->>e.kind<>'true') OR NOT public.push_target_allowed(e.user_id,e.kind,e.target));
 WITH candidates AS (SELECT d.id FROM public.push_deliveries d WHERE d.state='queued' AND d.next_attempt<=now()
   ORDER BY d.id FOR UPDATE SKIP LOCKED LIMIT greatest(1,least(p_limit,40))),
 leased AS (UPDATE public.push_deliveries d SET attempts=d.attempts+1,lease=gen_random_uuid(),next_attempt=now()+interval '2 minutes'
   FROM candidates c WHERE d.id=c.id RETURNING d.*)
 SELECT COALESCE(jsonb_agg(jsonb_build_object('id',d.id,'lease',d.lease,'notification_id',e.id,'kind',e.kind,'target',e.target,
   'endpoint',s.endpoint,'p256dh',s.p256dh,'auth',s.auth,'language',s.language,'binding',s.binding)),'[]'::jsonb)
 INTO v_jobs FROM leased d JOIN public.push_events e ON e.id=d.event_id JOIN public.push_subscriptions s ON s.id=d.subscription_id;
 RETURN v_jobs;
END $$;
REVOKE ALL ON FUNCTION public.push_claim(integer) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.push_claim(integer) TO service_role;

CREATE FUNCTION public.push_finish(p_id bigint,p_lease uuid,p_status integer) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_sub bigint;
BEGIN
 IF p_status IN (404,410) THEN
  SELECT subscription_id INTO v_sub FROM public.push_deliveries WHERE id=p_id AND lease=p_lease AND state='queued';
  DELETE FROM public.push_subscriptions WHERE id=v_sub; RETURN;
 END IF;
 UPDATE public.push_deliveries SET state=CASE WHEN p_status BETWEEN 200 AND 299 THEN 'sent'
   WHEN p_status=0 OR p_status=429 OR p_status>=500 THEN CASE WHEN attempts>=5 THEN 'dropped' ELSE 'queued' END ELSE 'dropped' END,
   next_attempt=now()+interval '1 minute'*power(2,least(attempts-1,4)),status_code=p_status
 WHERE id=p_id AND lease=p_lease AND state='queued';
END $$;
REVOKE ALL ON FUNCTION public.push_finish(bigint,uuid,integer) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.push_finish(bigint,uuid,integer) TO service_role;

CREATE FUNCTION public.push_event_trigger() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_team integer; v_player integer; v_user integer; v_event integer; v_kind text; v_target jsonb; v_reason text; v_key text;
BEGIN
 v_key=TG_TABLE_NAME||':'||txid_current()::text||':';
 IF TG_TABLE_NAME='friend_requests' THEN
  IF NEW.status='pending' THEN PERFORM public.push_enqueue(NEW.recipient_id,'friends',jsonb_build_object('mode','friends','id',NEW.id),v_key||NEW.id); END IF;
 ELSIF TG_TABLE_NAME='portal_notices' THEN
  FOR v_user,v_player IN SELECT user_id,player_id FROM public.portal_player_links WHERE team_id=NEW.team_id LOOP
   PERFORM public.push_enqueue(v_user,'notices',jsonb_build_object('mode','player','team_id',NEW.team_id,'player_id',v_player,'id',NEW.id),v_key||NEW.id);
  END LOOP;
 ELSIF TG_TABLE_NAME='portal_callups' THEN
  IF TG_OP='UPDATE' AND (NEW.meeting_time,NEW.meeting_place,NEW.note) IS NOT DISTINCT FROM (OLD.meeting_time,OLD.meeting_place,OLD.note) THEN RETURN NEW; END IF;
  IF TG_OP='DELETE' THEN v_event=OLD.match_id;v_player=OLD.player_id;v_reason='withdrawn';
  ELSE v_event=NEW.match_id;v_player=NEW.player_id;v_reason=CASE WHEN TG_OP='INSERT' THEN 'new' ELSE 'changed' END; END IF;
  SELECT id_taldea INTO v_team FROM public.partidak WHERE id_partida=v_event;
  SELECT user_id INTO v_user FROM public.portal_player_links WHERE player_id=v_player AND team_id=v_team;
  IF v_user IS NOT NULL THEN PERFORM public.push_enqueue(v_user,'callups',jsonb_build_object('mode','player','team_id',v_team,'player_id',v_player,'kind','match','event_id',v_event,'reason',v_reason),v_key||v_event||':'||v_player); END IF;
 ELSIF TG_TABLE_NAME='portal_event_responses' THEN
  IF TG_OP='UPDATE' AND (NEW.response,NEW.note) IS NOT DISTINCT FROM (OLD.response,OLD.note) THEN RETURN NEW; END IF;
  IF NEW.kind='session' THEN SELECT id_taldea INTO v_team FROM public.saioak WHERE id_saio=NEW.event_id;
  ELSE SELECT id_taldea INTO v_team FROM public.partidak WHERE id_partida=NEW.event_id; END IF;
  FOR v_user IN SELECT user_id FROM public.team_memberships WHERE team_id=v_team AND user_id<>NEW.user_id LOOP
   PERFORM public.push_enqueue(v_user,'responses',jsonb_build_object('mode','coach','team_id',v_team,'kind',NEW.kind,'event_id',NEW.event_id),v_key||NEW.player_id||':'||NEW.kind||':'||NEW.event_id);
  END LOOP;
 ELSE
  IF TG_OP='UPDATE' AND (NEW.data_ordua,NEW.lekua) IS NOT DISTINCT FROM (OLD.data_ordua,OLD.lekua) THEN RETURN NEW; END IF;
  IF left(NEW.data_ordua,10)<to_char(current_date,'YYYY-MM-DD') THEN RETURN NEW; END IF;
  v_team=NEW.id_taldea;
  IF TG_TABLE_NAME='saioak' THEN v_event=NEW.id_saio;v_kind='session'; ELSE v_event=NEW.id_partida;v_kind='match'; END IF;
  FOR v_user,v_player IN SELECT l.user_id,l.player_id FROM public.portal_player_links l WHERE l.team_id=v_team
   AND (v_kind='session' OR EXISTS(SELECT 1 FROM public.portal_callups c WHERE c.match_id=v_event AND c.player_id=l.player_id)) LOOP
   PERFORM public.push_enqueue(v_user,CASE WHEN TG_OP='INSERT' THEN 'callups' ELSE 'schedule' END,jsonb_build_object('mode','player','team_id',v_team,'player_id',v_player,'kind',v_kind,'event_id',v_event,'reason',CASE WHEN TG_OP='INSERT' THEN 'new' ELSE 'changed' END),v_key||v_event);
  END LOOP;
 END IF;
 RETURN NULL;
END $$;
REVOKE ALL ON FUNCTION public.push_event_trigger() FROM PUBLIC,anon,authenticated;
CREATE TRIGGER push_friend_request AFTER INSERT ON public.friend_requests FOR EACH ROW EXECUTE FUNCTION public.push_event_trigger();
CREATE TRIGGER push_notice AFTER INSERT ON public.portal_notices FOR EACH ROW EXECUTE FUNCTION public.push_event_trigger();
CREATE TRIGGER push_callup AFTER INSERT OR UPDATE OR DELETE ON public.portal_callups FOR EACH ROW EXECUTE FUNCTION public.push_event_trigger();
CREATE TRIGGER push_response AFTER INSERT OR UPDATE ON public.portal_event_responses FOR EACH ROW EXECUTE FUNCTION public.push_event_trigger();
CREATE TRIGGER push_session_schedule AFTER INSERT OR UPDATE ON public.saioak FOR EACH ROW EXECUTE FUNCTION public.push_event_trigger();
CREATE TRIGGER push_match_schedule AFTER UPDATE ON public.partidak FOR EACH ROW EXECUTE FUNCTION public.push_event_trigger();
