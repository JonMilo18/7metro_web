CREATE TABLE public.push_subscriptions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id integer NOT NULL REFERENCES public.erabiltzaileak(id_erabiltzailea) ON DELETE CASCADE,
 device_hash text NOT NULL UNIQUE CHECK(device_hash ~ '^[0-9a-f]{64}$'),
 session_hash text NOT NULL, endpoint text NOT NULL UNIQUE CHECK(length(endpoint)<=2048 AND endpoint LIKE 'https://%'),
 p256dh text NOT NULL, auth text NOT NULL, binding text NOT NULL DEFAULT gen_random_uuid()::text,
 language text NOT NULL DEFAULT 'eu' CHECK(language IN ('eu','es')),
 preferences jsonb NOT NULL DEFAULT '{"callups":true,"schedule":true,"notices":true,"responses":true,"friends":true}',
 last_test_at timestamptz, updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK(jsonb_typeof(preferences)='object' AND preferences ?& ARRAY['callups','schedule','notices','responses','friends'] AND jsonb_typeof(preferences->'callups')='boolean'
 AND jsonb_typeof(preferences->'schedule')='boolean' AND jsonb_typeof(preferences->'notices')='boolean'
 AND jsonb_typeof(preferences->'responses')='boolean' AND jsonb_typeof(preferences->'friends')='boolean')
);
CREATE INDEX push_subscriptions_user ON public.push_subscriptions(user_id);
CREATE INDEX push_subscriptions_session ON public.push_subscriptions(session_hash);
CREATE TABLE public.push_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id integer NOT NULL REFERENCES public.erabiltzaileak(id_erabiltzailea) ON DELETE CASCADE,
 kind text NOT NULL CHECK(kind IN ('callups','schedule','notices','responses','friends','test')),
 target jsonb NOT NULL, dedupe_key text NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(user_id,dedupe_key)
);
CREATE TABLE public.push_deliveries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id bigint NOT NULL REFERENCES public.push_events(id) ON DELETE CASCADE,
 subscription_id bigint NOT NULL REFERENCES public.push_subscriptions(id) ON DELETE CASCADE,
 state text NOT NULL DEFAULT 'queued' CHECK(state IN ('queued','sent','dropped')),
 attempts integer NOT NULL DEFAULT 0, next_attempt timestamptz NOT NULL DEFAULT now(), lease uuid, status_code integer,
 UNIQUE(event_id,subscription_id)
);
CREATE INDEX push_events_created ON public.push_events(created_at);
CREATE INDEX push_deliveries_pending ON public.push_deliveries(next_attempt) WHERE state='queued';
CREATE TABLE public.push_worker_wakes(nonce uuid PRIMARY KEY,issued_at bigint NOT NULL,consumed_at timestamptz);
