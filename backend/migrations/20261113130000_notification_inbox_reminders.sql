CREATE TABLE public.notification_inbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES public.erabiltzaileak(id_erabiltzailea) ON DELETE CASCADE,
  kind text NOT NULL CHECK(kind IN ('callups','schedule','notices','responses','friends')),
  target jsonb NOT NULL,
  dedupe_key text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz,
  UNIQUE(user_id,dedupe_key)
