CREATE OR REPLACE FUNCTION public.push_target_allowed(p_user integer,p_kind text,p_target jsonb) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_team integer; v_player integer; v_event integer;
BEGIN
 IF p_kind='test' THEN RETURN true; END IF;
 IF p_kind='friends' THEN RETURN EXISTS(SELECT 1 FROM public.friend_requests WHERE id=(p_target->>'id')::bigint AND recipient_id=p_user AND status='pending'); END IF;
 v_team=(p_target->>'team_id')::integer; v_event=(p_target->>'event_id')::integer;
 IF p_target->>'mode'='coach' THEN
   RETURN EXISTS(SELECT 1 FROM public.team_memberships WHERE team_id=v_team AND user_id=p_user);
 END IF;
 v_player=(p_target->>'player_id')::integer;
 IF p_target->>'reason'='reminder' THEN
   IF EXISTS(SELECT 1 FROM public.portal_event_responses r WHERE r.player_id=v_player AND r.user_id=p_user
     AND r.kind=p_target->>'kind' AND r.event_id=v_event) THEN RETURN false; END IF;
   IF p_target->>'kind'='session' THEN
     IF NOT EXISTS(SELECT 1 FROM public.saioak WHERE id_saio=v_event AND id_taldea=v_team
       AND data_ordua=p_target->>'event_date' AND public.notification_event_time(data_ordua)>now()) THEN RETURN false; END IF;
   ELSE
     IF NOT EXISTS(SELECT 1 FROM public.partidak WHERE id_partida=v_event AND id_taldea=v_team
       AND data_ordua=p_target->>'event_date' AND public.notification_event_time(data_ordua)>now()) THEN RETURN false; END IF;
   END IF;
 END IF;
 IF NOT EXISTS(SELECT 1 FROM public.portal_player_links l JOIN public.jokalariak j ON j.id_jokalaria=l.player_id AND j.id_taldea=l.team_id
  WHERE l.user_id=p_user AND l.player_id=v_player AND l.team_id=v_team) THEN RETURN false; END IF;
 IF p_kind='notices' THEN RETURN EXISTS(SELECT 1 FROM public.portal_notices WHERE id=(p_target->>'id')::bigint AND team_id=v_team); END IF;
 IF p_target->>'kind'='session' THEN RETURN EXISTS(SELECT 1 FROM public.saioak WHERE id_saio=v_event AND id_taldea=v_team); END IF;
 IF p_target->>'kind'='match' THEN
   RETURN EXISTS(SELECT 1 FROM public.partidak m WHERE m.id_partida=v_event AND m.id_taldea=v_team AND
     (p_target->>'reason'='withdrawn' OR EXISTS(SELECT 1 FROM public.portal_callups WHERE match_id=v_event AND player_id=v_player)));
 END IF;
 RETURN false;
END $$;
REVOKE ALL ON FUNCTION public.push_target_allowed(integer,text,jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.push_target_allowed(integer,text,jsonb) TO service_role;


CREATE OR REPLACE FUNCTION public.push_enqueue(p_user integer,p_kind text,p_target jsonb,p_key text,p_subscription bigint DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_event bigint; v_inbox bigint;
BEGIN
 IF p_kind<>'test' THEN
  INSERT INTO public.notification_inbox(user_id,kind,target,dedupe_key) VALUES(p_user,p_kind,p_target,p_key)
  ON CONFLICT(user_id,dedupe_key) DO NOTHING RETURNING id INTO v_inbox;
  IF v_inbox IS NULL THEN RETURN; END IF;
 END IF;
 IF NOT EXISTS(SELECT 1 FROM public.push_subscriptions s JOIN public.api_sessions a ON a.token_hash=s.session_hash AND a.user_id=s.user_id
   WHERE s.user_id=p_user AND a.expires_at>extract(epoch FROM now()) AND (p_subscription IS NULL OR s.id=p_subscription)
   AND (p_kind='test' OR s.preferences->>p_kind='true')) THEN RETURN; END IF;
 INSERT INTO public.push_events(user_id,kind,target,dedupe_key) VALUES(p_user,p_kind,p_target,p_key)
 ON CONFLICT(user_id,dedupe_key) DO NOTHING RETURNING id INTO v_event;
 IF v_event IS NULL THEN RETURN; END IF;
 INSERT INTO public.push_deliveries(event_id,subscription_id)
 SELECT v_event,s.id FROM public.push_subscriptions s JOIN public.api_sessions a ON a.token_hash=s.session_hash AND a.user_id=s.user_id
 WHERE s.user_id=p_user AND a.expires_at>extract(epoch FROM now()) AND (p_subscription IS NULL OR s.id=p_subscription)
 AND (p_kind='test' OR s.preferences->>p_kind='true');
 -- Keep durable deliveries when the optional network wake fails; cron retries them.
 BEGIN
  PERFORM public.push_wake_worker();
 EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Push worker wake failed (SQLSTATE %); deliveries remain queued',SQLSTATE;
 END;
END $$;
REVOKE ALL ON FUNCTION public.push_enqueue(integer,text,jsonb,text,bigint) FROM PUBLIC,anon,authenticated;


COMMIT;
