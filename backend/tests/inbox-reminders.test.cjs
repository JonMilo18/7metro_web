async function fixture() {
  const db = new PGlite();
  const source = fs.readFileSync(path.join(__dirname, 'portal-actions.test.cjs'), 'utf8');
  await db.exec(source.match(/await db\.exec\(`([\s\S]*?)`\);/)[1]);
  await db.exec(`CREATE TABLE api_sessions(token_hash text PRIMARY KEY,user_id integer,expires_at double precision);
    CREATE TABLE friend_requests(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,requester_id integer,recipient_id integer,status text);`);
  for (const file of ['20261112120000_player_portal.sql', '20261112130000_preserve_callup_responses.sql',
    '20261112140000_web_push.sql', '20261113130000_notification_inbox_reminders.sql']) {
    await db.exec(fs.readFileSync(path.join(__dirname, '../migrations', file), 'utf8'));
  }
  return db;
}
async function inbox(db, user, action = 'list', data = {}) {
  return (await db.query('SELECT notification_inbox_action($1,$2,$3::jsonb) AS result', [user, action, JSON.stringify(data)])).rows[0].result;
}
async function subscribe(db) {
  await db.exec(`INSERT INTO api_sessions VALUES(repeat('b',64),2,'Infinity');
    INSERT INTO push_subscriptions(user_id,device_hash,session_hash,endpoint,p256dh,auth)
    VALUES(2,repeat('2',64),repeat('b',64),'https://web.push.apple.com/fixture','fixture','fixture');`);
}

test('inbox records events without push permission and isolates users, read receipts and revoked access', async () => {
  const db = await fixture();
  try {
    await db.exec("INSERT INTO portal_player_links(player_id,team_id,user_id) VALUES(10,7,2); INSERT INTO portal_notices(team_id,title,body) VALUES(7,'Team notice','PRIVATE NOTE');");
    const list = await inbox(db, 2);
    assert.equal(list.unread, 1);
    assert.equal(list.items[0].team_name, 'Taldea');
    assert(!JSON.stringify(list).includes('PRIVATE NOTE'));
    assert.equal((await inbox(db, 3)).items.length, 0);
    await assert.rejects(inbox(db, 3, 'open', { id: list.items[0].id }), error => error.code === 'P0002');
    assert.equal((await inbox(db, 2, 'count')).unread, 1);
    const opened = await inbox(db, 2, 'open', { id: list.items[0].id });
    assert.equal(opened.kind, 'notices');
    assert.equal((await inbox(db, 2, 'count')).unread, 0);
    assert.equal((await inbox(db, 2)).items[0].read, true);
    await db.exec("INSERT INTO friend_requests(requester_id,recipient_id,status) VALUES(1,2,'pending');");
    assert.equal((await inbox(db, 2, 'count')).unread, 1);
    await inbox(db, 3, 'read_all');
    assert.equal((await inbox(db, 2, 'count')).unread, 1);
    await inbox(db, 2, 'read_all');
    assert.equal((await inbox(db, 2, 'count')).unread, 0);
    await db.exec('DELETE FROM portal_player_links WHERE player_id=10');
    assert.equal((await inbox(db, 2)).items.length, 1, 'Revoked team access removes team notifications while keeping own friend requests');
    const rights = (await db.query("SELECT has_table_privilege('anon','notification_inbox','select') AS read, has_function_privilege('authenticated','notification_inbox_action(integer,text,jsonb)','execute') AS rpc")).rows[0];
    assert.equal(rights.read, false);
    assert.equal(rights.rpc, false);
  } finally { await db.close(); }
});

test('inbox pagination has no overlap and push clicks acknowledge only the authenticated recipient', async () => {
  const db = await fixture();
  try {
    await db.exec("INSERT INTO portal_player_links(player_id,team_id,user_id) VALUES(10,7,2)");
    await subscribe(db);
    await db.exec("INSERT INTO portal_notices(team_id,title,body) SELECT 7,'Notice '||n,'Body' FROM generate_series(1,35) n");
    const first = await inbox(db, 2);
    assert.equal(first.items.length, 30);
    assert.equal(first.has_more, true);
    const second = await inbox(db, 2, 'list', { before: first.items.at(-1).id });
    assert.equal(second.items.length, 5);
    assert.equal(second.has_more, false);
    assert.equal(new Set([...first.items, ...second.items].map(item => item.id)).size, 35);
    const push = (await db.query('SELECT id FROM push_events ORDER BY id DESC LIMIT 1')).rows[0];
    await inbox(db, 3, 'ack_push', push);
    assert.equal((await inbox(db, 2, 'count')).unread, 35);
    await inbox(db, 2, 'ack_push', push);
    assert.equal((await inbox(db, 2, 'count')).unread, 34);
    await assert.rejects(inbox(db, 2, 'list', { before: 'invalid' }), error => error.code === '22023');
  } finally { await db.close(); }
});

test('24-hour and 3-hour reminders skip replies and unselected players and survive retries without duplicates', async () => {
  const db = await fixture();
  try {
    const now = new Date();
    const training = new Date(now.getTime() + 20 * 3600000).toISOString();
    const match = new Date(now.getTime() + 2 * 3600000).toISOString();
    await db.query('UPDATE saioak SET data_ordua=$1 WHERE id_saio=100', [training]);
    await db.query('UPDATE partidak SET data_ordua=$1 WHERE id_partida=200', [match]);
    await db.exec("INSERT INTO portal_player_links(player_id,team_id,user_id) VALUES(10,7,2)");
    await subscribe(db);
    const remind = async (value = now) => (await db.query('SELECT send_callup_reminders($1::timestamptz) AS n', [value.toISOString()])).rows[0].n;
    assert.equal(await remind(), 1, 'Only the training is eligible before the match callup is published');
    assert.equal(await remind(), 0);
    await db.exec('INSERT INTO portal_callups(match_id,player_id) VALUES(200,10)');
    assert.equal(await remind(), 1);
    const reminders = (await db.query("SELECT * FROM notification_inbox WHERE target->>'reason'='reminder'")).rows;
    assert.deepEqual(reminders.map(item => item.target.stage).sort(), ['24h', '3h']);
    assert.equal(await remind(new Date(now.getTime() + 18 * 3600000)), 1, 'A training gets one second reminder in the three-hour window');
    assert.equal(await remind(new Date(now.getTime() + 18 * 3600000)), 0);
    await db.exec("INSERT INTO portal_event_responses(player_id,kind,event_id,user_id,response) VALUES(10,'session',100,2,'maybe'),(10,'match',200,2,'no')");
    assert.equal(await remind(), 0, 'Every submitted response stops reminders, including maybe and no');
    const jobs = (await db.query('SELECT push_claim(40) AS jobs')).rows[0].jobs;
    assert(!jobs.some(job => job.target.reason === 'reminder'), 'Replies also cancel queued reminders before delivery');
    assert(!(await inbox(db, 2)).items.some(item => item.target.reason === 'reminder'));
    await db.exec("DELETE FROM portal_event_responses; UPDATE saioak SET data_ordua='invalid' WHERE id_saio=100; DELETE FROM portal_callups;");
    assert.equal(await remind(), 0);
  } finally { await db.close(); }
});

test('local event times use Madrid daylight saving rules and stale reminders become unavailable', async () => {
  const db = await fixture();
  try {
    const times = (await db.query("SELECT notification_event_time('2028-01-10T18:00') AT TIME ZONE 'UTC' AS winter, notification_event_time('2028-07-10T18:00') AT TIME ZONE 'UTC' AS summer, notification_event_time('bad') AS invalid")).rows[0];
    assert(String(times.winter).includes('17:00'));
    assert(String(times.summer).includes('16:00'));
    assert.equal(times.invalid, null);
    await db.exec("INSERT INTO portal_player_links(player_id,team_id,user_id) VALUES(10,7,2)");
    const date = new Date(Date.now() + 2 * 3600000).toISOString();
    await db.query('UPDATE saioak SET data_ordua=$1 WHERE id_saio=100', [date]);
    await db.query('SELECT send_callup_reminders(now())');
    const item = (await inbox(db, 2)).items.find(item => item.target.reason === 'reminder');
    assert(item);
    await db.query('UPDATE saioak SET data_ordua=$1 WHERE id_saio=100', [new Date(Date.now() + 30 * 3600000).toISOString()]);
    await assert.rejects(inbox(db, 2, 'open', { id: item.id }), error => error.code === 'P0002');
  } finally { await db.close(); }
});

test('inbox gateway uses session ownership and sanitizes database errors', async () => {
  const context = {};
  vm.createContext(context);
  const source = stripTypeScriptTypes(fs.readFileSync(path.join(__dirname, '../inbox-actions.ts'), 'utf8'));
  vm.runInContext(source.replace(/^import .*;\r?\n/gm, '').replace(/export /g, '') + '\nthis.handle=handleInboxAction;', context);
  let args;
  const respond = (status, body) => ({ status, body });
  const client = { rpc: async (name, parameters) => { args = parameters; return { data: { unread: 0 } }; } };
  assert.equal((await context.handle({ action: 'inbox_count', user_id: 99 }, client, 2, respond)).status, 200);
  assert.equal(args.p_user, 2);
  const failed = await context.handle({ action: 'inbox_count' }, { rpc: async () => ({ error: { code: 'XX000', message: 'PRIVATE' } }) }, 2, respond);
  assert.equal(failed.status, 500);
  assert(!JSON.stringify(failed).includes('PRIVATE'));
});
